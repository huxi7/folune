-- 六个主题簇（含一个刻意近似的「读书简记」，用于验证结构通道按真实父目录判断）
insert into public.memo_nodes (user_id, parent_id, node_type, title, sort_order, created_at, updated_at)
select
  u.id,
  null,
  'folder',
  folder.title,
  folder.ord * 1000,
  now() - interval '150 days',
  now() - interval '150 days'
from (select id from public.profiles where username = 'link') u
cross join (values
  ('系统设计', 1), ('产品思考', 2), ('读书笔记', 3),
  ('学习笔记', 4), ('写作与表达', 5), ('日常思考', 6), ('读书简记', 7)
) as folder(title, ord);

-- 备忘录节点
insert into public.memo_nodes (user_id, parent_id, node_type, title, sort_order, created_at, updated_at)
select
  u.id,
  parent.id,
  'memo',
  c.title,
  row_number() over (partition by c.folder order by c.day_offset desc) * 1000,
  now() - make_interval(days => c.day_offset),
  now() - make_interval(days => c.day_offset)
from seed_corpus c
cross join (select id from public.profiles where username = 'link') u
join public.memo_nodes parent
  on parent.user_id = u.id
  and parent.node_type = 'folder'
  and parent.title = c.folder;

-- 正文。excerpt/word_count 按 api 的派生规则：摘要取正文前 200 字，字数取字符数
insert into public.memos (node_id, user_id, content_mdx, excerpt, word_count, created_at, updated_at)
select
  node.id,
  node.user_id,
  c.body,
  left(c.body, 200),
  length(c.body),
  node.created_at,
  node.created_at
from seed_corpus c
join public.memo_nodes node
  on node.user_id = (select id from public.profiles where username = 'link')
  and node.node_type = 'memo'
  and node.title = c.title;
